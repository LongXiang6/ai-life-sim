# Purpose: Render and persist the checker Markdown summary.
# Owner: quality:infrastructure
# Responsibility: Markdown chart and issue-detail projection only.

function New-CheckerBarChart($value, $max, $width = 30) {
  $filled = [Math]::Max(1, [Math]::Floor($value / [Math]::Max(1, $max) * $width))
  $block = [string][char]0x2588
  $shade = [string][char]0x2591
  return ($block * $filled) + ($shade * ($width - $filled))
}

function Save-MarkdownCheckerReport($summary, $modCount, $categoryStats, $ruleStats, $results, $outputDir, $timestamp) {
  $mdPath = Join-Path $outputDir "checker-${timestamp}.md"
  $maxCatVal = 0
  foreach ($cv in $categoryStats.Values) {
    $value = $cv.Errors + $cv.Warnings
    if ($value -gt $maxCatVal) { $maxCatVal = $value }
  }
  $maxRuleVal = 0
  foreach ($count in $ruleStats.Values) {
    if ($count -gt $maxRuleVal) { $maxRuleVal = $count }
  }

  $totalIssues = $summary.Errors + $summary.Warnings
  $errRate = if ($totalIssues -gt 0) { [Math]::Round($summary.Errors / $totalIssues * 100) } else { 0 }
  $warnRate = 100 - $errRate
  $md = [System.Text.StringBuilder]::new()
  [void]$md.AppendLine("# Check Report - $($summary.Timestamp)")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("## Summary")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("| Metric | Value |")
  [void]$md.AppendLine("|--------|-------|")
  [void]$md.AppendLine("| MODs Scanned | $modCount |")
  [void]$md.AppendLine("| Total Checks | $($summary.Total) |")
  [void]$md.AppendLine("| Errors (FAIL) | $($summary.Errors) |")
  [void]$md.AppendLine("| Warnings (WARN) | $($summary.Warnings) |")
  [void]$md.AppendLine("| Passed (OK) | $($summary.Pass) |")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("### Error/Warning Distribution")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("``````")
  $errChart = New-CheckerBarChart $summary.Errors $totalIssues 30
  $warnChart = New-CheckerBarChart $summary.Warnings $totalIssues 30
  [void]$md.AppendLine("Errors: $errChart ${errRate}%")
  [void]$md.AppendLine("Warnings: $warnChart ${warnRate}%")
  [void]$md.AppendLine("``````")
  [void]$md.AppendLine("")

  [void]$md.AppendLine("## By Category")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("| Category | Errors | Warnings | Total | Chart |")
  [void]$md.AppendLine("|------|------|------|------|--------|")
  foreach ($kv in ($categoryStats.GetEnumerator() | Sort-Object { $_.Value.Errors + $_.Value.Warnings } -Descending)) {
    $catTotal = $kv.Value.Errors + $kv.Value.Warnings
    $chart = New-CheckerBarChart $catTotal $maxCatVal 15
    [void]$md.AppendLine("| $($kv.Key) | $($kv.Value.Errors) | $($kv.Value.Warnings) | $catTotal | $chart |")
  }
  [void]$md.AppendLine("")

  [void]$md.AppendLine("## Top 20 Files with Most Issues")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("| File | Errors | Warnings | Total | Chart |")
  [void]$md.AppendLine("|------|------|------|------|--------|")
  $maxFileTotal = 0
  foreach ($fileSummary in $summary.TopFiles) {
    $fileTotal = $fileSummary.Errors + $fileSummary.Warnings
    if ($fileTotal -gt $maxFileTotal) { $maxFileTotal = $fileTotal }
  }
  foreach ($fileSummary in $summary.TopFiles) {
    $fileTotal = $fileSummary.Errors + $fileSummary.Warnings
    $chart = New-CheckerBarChart $fileTotal $maxFileTotal 10
    [void]$md.AppendLine("| $($fileSummary.File) | $($fileSummary.Errors) | $($fileSummary.Warnings) | $fileTotal | $chart |")
  }
  [void]$md.AppendLine("")

  [void]$md.AppendLine("## Top 20 Rules Triggered")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("| Rule | Count | Chart |")
  [void]$md.AppendLine("|------|------|--------|")
  foreach ($ruleSummary in $summary.TopRules) {
    $chart = New-CheckerBarChart $ruleSummary.Count $maxRuleVal 20
    [void]$md.AppendLine("| $($ruleSummary.Rule) | $($ruleSummary.Count) | $chart |")
  }
  [void]$md.AppendLine("")

  [void]$md.AppendLine("## All Error Details")
  [void]$md.AppendLine("")
  $errorResults = @($results | Where-Object { $_.Level -eq 'ERROR' })
  if ($errorResults.Count -eq 0) {
    [void]$md.AppendLine("> No errors")
  } else {
    foreach ($errorResult in $errorResults) {
      [void]$md.AppendLine("- **[$($errorResult.Rule)]** ``$($errorResult.File)`` L$($errorResult.Line) : $($errorResult.Message)")
    }
  }
  [void]$md.AppendLine("")
  [void]$md.AppendLine("---")
  [void]$md.AppendLine("")
  [void]$md.AppendLine("*Report auto-generated by project-checker - $($summary.Total) total checks*")

  $md.ToString() | Set-Content -Path $mdPath -Encoding UTF8
  Write-Host "  Markdown report: $mdPath" -ForegroundColor DarkGray
}
